    @staticmethod
    def get_user_agent_for_version(chrome_version: str = "128") -> str:
        """
        Retorna um user-agent aleatório para a versão do Chrome solicitada.
        Se a versão não existir, cai de volta para a mais recente (128).
        """
        agents = ChromeUserAgent.CHROME_USER_AGENTS.get(chrome_version)
        if not agents:
            agents = ChromeUserAgent.CHROME_USER_AGENTS.get("134")  # fallback para mais recente
        return random.choice(agents)

    @staticmethod
    def get_random_user_agent() -> str:
        """Retorna um user-agent aleatório de qualquer versão disponível."""
        all_agents = []
        for agents in ChromeUserAgent.CHROME_USER_AGENTS.values():
            all_agents.extend(agents)
        return random.choice(all_agents)

    @staticmethod
    def get_version_variants(chrome_version: str = "128", count: int = 5) -> list[str]:
        """
        Retorna 'count' user-agents diferentes para a mesma versão major.
        Se count > quantidade disponível, repete com reposição.
        """
        agents = ChromeUserAgent.CHROME_USER_AGENTS.get(
            chrome_version, ChromeUserAgent.CHROME_USER_AGENTS.get("128")
        )
        return random.choices(agents, k=min(count, len(agents)))


